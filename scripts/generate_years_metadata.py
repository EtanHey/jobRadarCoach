"""Generate SQL from the UI's shared experience grammar; no database access."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sql_regex(pattern):
    boundary = r"(?:(?<![A-Za-z0-9_])(?=[A-Za-z0-9_])|(?<=[A-Za-z0-9_])(?![A-Za-z0-9_]))"
    whitespace = r"[ \t\n\r\f\v\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]"
    return pattern.replace(r"\b", boundary).replace(r"\w", "A-Za-z0-9_").replace(r"\s", whitespace).replace("'", "''")


def generate():
    spec = json.loads((ROOT / "ui/lib/experience-patterns.json").read_text())
    number = spec["number"]
    lead = rf"(?<![A-Za-z0-9_.])(?:(?:at least|minimum(?:[ \t]+of)?|over|around)[ \t]+)?{number}(?:[ \t]*(?:[-–—]|to)[ \t]*{number})?\+?(?:[ \t]+or more)?[ \t]+(?:overall[ \t]+)?years?\b"
    branches = [lead + tail for tail in spec["englishTail"]] + [spec["hebrew"]]
    original = (ROOT / "supabase/migrations/0024_list_metadata.sql").read_text()
    technologies = original[original.index("  select coalesce(array_agg"):original.index("  loop\n")]
    utf16_prefix = original[original.index("    -- JS slice"):original.index("    section :=")]
    utf16_suffix = original[original.index("    short_suffix :="):original.index("    if (near_context")]
    regexes = ",\n".join("    '" + sql_regex(pattern) + "'" for pattern in branches)
    sql_pattern_0 = sql_regex(r'\s+(?:with|and|in|who|that)$')
    sql_pattern_1 = sql_regex(r'^\s*(?:[,;:–—-]\s*)?(?:is\s+)?(?:not required|not necessary|optional|nice to have|a plus|preferred)\b')
    sql_pattern_2 = sql_regex(r'\b(?:has|have)\s*$')
    sql_pattern_3 = sql_regex(r'\b(?:you|must)\s+have\s*$')
    sql_pattern_4 = sql_regex(r'\b(?:our|the|this)\s+(?:company|firm|business)\b[^.!?\n]{0,100}$')
    sql_pattern_5 = sql_regex(r'\bour team\s+(?:has|combines|brings|boasts|offers)\b[^.!?\n]{0,80}$')
    sql_pattern_6 = sql_regex(r"\bwe(?:'ve| have| bring| offer| boast)\b[^.!?\n]{0,80}$")
    sql_pattern_7 = sql_regex(r'^\s*(?:serving (?:customers|clients)|in business|as a company)\b')
    sql_pattern_8 = sql_regex(r"\b(?:you (?:need|have|bring)|we (?:require|seek)|looking for|seeking|must(?: have)?|required|requirements?|minimum|all about you|your (?:experience|expertise)|what you bring|what you(?:'|’)ll need)\b")
    sql_pattern_9 = sql_regex(r'^(?:at least|minimum)\b')
    sql_pattern_10 = sql_regex(r'\b(?:software|engineering|developer|development|backend|frontend|full[- ]stack|devops|platform|infrastructure|data|hardware|verification|technical|programming|manufacturing|managing|product|sre)\b')
    sql_pattern_11 = original.split("'description_available',coalesce((description collate \"C\") ~ '")[1].split("',false)")[0]
    output = f"""-- GENERATED by scripts/generate_years_metadata.py; edit the shared grammar first.
-- Updates future description writes. Existing cached rows need an operator-owned backfill.
begin;
create or replace function public.posting_list_metadata(description text)
returns jsonb language plpgsql immutable security invoker set search_path = '' as $fn$
declare
  technologies text[];
  phrase_patterns constant text[] := array[
{regexes}
  ];
  position integer := 1;
  branch_pattern text; candidate_start integer; experience_branch boolean;
  start_at integer; end_at integer; quoted text; matched text; prefix text;
  near_context text; suffix text; continuation text; short_suffix text;
  utf16_units integer; heading text; captures text[]; section text;
  amounts integer[]; hebrew boolean; word_number boolean; optional boolean; company boolean; required boolean;
  experience text := null;
  strongest_minimum integer := -1;
begin
{technologies}  loop
    start_at := 0;
    foreach branch_pattern in array phrase_patterns loop
      candidate_start := regexp_instr(coalesce(description,'') collate "C", branch_pattern, position, 1, 0, 'i');
      if candidate_start > 0 and (start_at = 0 or candidate_start < start_at) then
        start_at := candidate_start;
        experience_branch := branch_pattern = phrase_patterns[1];
        end_at := regexp_instr(description collate "C", branch_pattern, position, 1, 1, 'i');
      end if;
    end loop;
    exit when start_at = 0;
    if experience_branch then
      end_at := regexp_instr(description collate "C", '(?<![A-Za-z0-9_])experience(?![A-Za-z0-9_])', start_at, 1, 1, 'i');
    end if;
    matched := substr(description,start_at,end_at-start_at);
    position := end_at;
    select bool_or(m[1] ~* '^[a-z]'), array_agg(case when m[1] ~ '^[0-9]+$' then m[1]::integer
      else array_position(array{str(spec['words']).replace(chr(34), chr(39))}::text[],lower(m[1])) - 1 end)
      into word_number, amounts from regexp_matches(matched collate "C", '(?<![A-Za-z0-9_])({sql_regex(number)})(?![A-Za-z0-9_])','gi') m;
    if array_length(amounts,1) > 1 and amounts[2] < amounts[1] then continue; end if;
    quoted := regexp_replace(matched collate "C", '^minimum(?:[ \\t]+of)?[ \\t]+','','i');
    quoted := regexp_replace(quoted collate "C", '{sql_pattern_0}','','i');
    quoted := regexp_replace(quoted,'[.,;:]+$','');
    prefix := substr(description,1,start_at-1);
    near_context := right(btrim(regexp_replace(prefix,'^.*[.!?\\n]','','s'), E' \\t\\r'),180);
{utf16_prefix}    section := 'other';
    for captures in select regexp_matches(prefix collate "C",'{sql_regex(spec['headings'])}','gin') loop
      heading := btrim(regexp_replace(regexp_replace(coalesce(captures[1],captures[2],captures[3]),'[:#*]+$',''),'^[^A-Za-zא-ת]+',''));
      if (heading collate "C") ~* '{sql_regex(spec['optionalHeading'])}' then section := 'optional';
      elsif (heading collate "C") ~* '{sql_regex(spec['requiredHeading'])}' then section := 'applicant';
      elsif (heading collate "C") ~* '{sql_regex(spec['otherHeading'])}' then section := 'other'; end if;
    end loop;
    suffix := (regexp_split_to_array(substr(description,end_at),'[.!?\\n;]'))[1];
    continuation := coalesce(substring(substr(description,end_at) from '^[^\\n]*\\n[ \\t]+(?:or|או)(?=[[:space:]])[^\\n]*'),'');
    hebrew := matched ~ '[א-ת]';
    if ((near_context || ' ' || case when hebrew then '' else matched end || ' ' || suffix || ' ' || continuation) collate "C") ~* '{sql_regex(spec['reject'])}' then continue; end if;
    if (near_context collate "C") ~* '(?<![A-Za-z0-9_])(?:{sql_regex(number)})[ -]*$' then continue; end if;
    if hebrew and not (near_context ~ '{sql_regex(spec['hebrewPrefix'])}') then continue; end if;
{utf16_suffix}    optional := section = 'optional' or (suffix collate "C") ~* '{sql_pattern_1}';
    company := ((near_context collate "C") ~* '{sql_pattern_2}' and not (near_context collate "C") ~* '{sql_pattern_3}')
      or (near_context collate "C") ~* '{sql_pattern_4}'
      or (near_context collate "C") ~* '{sql_pattern_5}'
      or (near_context collate "C") ~* '{sql_pattern_6}'
      or (suffix collate "C") ~* '{sql_pattern_7}';
    required := section = 'applicant'
      or (near_context collate "C") ~* '{sql_pattern_8}'
      or (matched collate "C") ~* '{sql_pattern_9}'
      or (hebrew and (matched ~ '^(?:לפחות|ניסיון של לפחות|נסיון של לפחות)' or near_context ~ 'נדרש|דרישות'))
      or (not word_number and ((matched || ' ' || short_suffix) collate "C") ~* '{sql_pattern_10}');
    if not optional and not company and required then
      if ((suffix || ' ' || continuation) collate "C") ~* '{sql_regex(spec['alternativeYears'].replace("{number}", number))}' then
        experience := null; exit;
      end if;
      if amounts[1] > strongest_minimum then
        strongest_minimum := amounts[1]; experience := quoted;
      end if;
    end if;
  end loop;
  return jsonb_build_object('stack',technologies,'experience',experience,
    'description_available',coalesce((description collate "C") ~ '{sql_pattern_11}',false));
end
$fn$;
revoke all on function public.posting_list_metadata(text) from public, anon, authenticated;
grant execute on function public.posting_list_metadata(text) to service_role;
commit;
"""
    return output


if __name__ == "__main__":
    (ROOT / "supabase/migrations/0039_years_metadata.sql").write_text(generate())
